-- Hyprland configuration (Lua) — https://wiki.hypr.land/Configuring/Start/

local apps = require("config.apps")

hl.config({ autogenerated = false })


hl.on("hyprland.start", function()
	-- start noctalia
	hl.exec_cmd(apps.launcher .. " -t service -- " .. apps.desktopShell)

	-- Limine + Snapper snapshot notifications
	hl.exec_cmd("command -v limine-snapper-restore >/dev/null && sleep 2 && " .. apps.launcher .. " -- limine-snapper-restore --notify ")

end)


-- Load the local configuration modules.
require("config.binds")
require("config.decorations")
require("config.inputs")
require("config.misc")
require("config.windowrules")
require("config.layerrules")
require("config.layouts")
require("config.animations")
require("config.gestures")
require("config.monitors")
require("config.workspaces")


-- For Noctalia Color templates
require("noctalia").apply_theme()
